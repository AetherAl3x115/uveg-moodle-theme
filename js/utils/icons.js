/**
 * Genera un <svg> con el ícono solicitado.
 *
 * @param {string} key       - Clave del mapa PATHS (p.ej. 'dashboard')
 * @param {number} size      - Tamaño en px (default 20)
 * @param {string} extraClass- Clase CSS adicional opcional
 * @returns {string}         - HTML string listo para innerHTML
 */
export function hi(key, size = 20, extraClass = "") {
  const paths = PATHS[key];
  if (!paths) {
    // Fallback: cuadrado vacío para detectar claves faltantes en dev
    console.warn(`[icons.js] Ícono no encontrado: "${key}"`);
    return `<svg width="${size}" height="${size}" viewBox="0 0 24 24"
      fill="none" xmlns="http://www.w3.org/2000/svg"
      aria-hidden="true" class="hi${extraClass ? " " + extraClass : ""}">
      <rect x="3" y="3" width="18" height="18" rx="2"
        stroke="currentColor" stroke-width="1.5" stroke-dasharray="4 2"/>
    </svg>`;
  }

  return `<svg
    xmlns="http://www.w3.org/2000/svg"
    width="${size}"
    height="${size}"
    viewBox="0 0 24 24"
    fill="none"
    stroke="currentColor"
    stroke-width="1.5"
    stroke-linecap="round"
    stroke-linejoin="round"
    aria-hidden="true"
    class="hi${extraClass ? " " + extraClass : ""}"
  >${paths}</svg>`;
}

